"""Export deterministic JSON Schema and TypeScript contracts from backend schemas."""

import json
from pathlib import Path

from services.core.contracts import (
    CostModel,
    DepthLevel,
    ExchangeSession,
    Instrument,
    Quote,
    RiskConfig,
    StrategyEnvelope,
    TradeDecision,
)
from services.core.execution import (
    ExecutionPolicy,
    FeeRule,
    FeeSchedule,
    PaperExecutionConfig,
    SourceEvidence,
)
from services.paper.contracts import FillBooking, ManualEntryIntent, OrderRequest, OrderRiskApproval

MODELS = (
    DepthLevel,
    Instrument,
    Quote,
    ExchangeSession,
    CostModel,
    RiskConfig,
    StrategyEnvelope,
    TradeDecision,
    SourceEvidence,
    FeeRule,
    FeeSchedule,
    ExecutionPolicy,
    PaperExecutionConfig,
    OrderRequest,
    ManualEntryIntent,
    FillBooking,
    OrderRiskApproval,
)


def ts_type(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts_type(part) for part in schema["anyOf"])
    kind = schema.get("type", "unknown")
    if kind == "object":
        if "properties" in schema:
            required = set(schema.get("required", []))
            fields = [
                f"{name}{'' if name in required else '?'}: {ts_type(value)};"
                for name, value in schema["properties"].items()
            ]
            return "{\n  " + "\n  ".join(fields) + "\n}"
        return f"Record<string, {ts_type(schema.get('additionalProperties', {}))}>"
    if kind == "array":
        return f"Array<{ts_type(schema.get('items', {}))}>"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def artifacts() -> dict[str, str]:
    definitions = {}
    output = {}
    for model in MODELS:
        schema = model.model_json_schema(mode="serialization")
        output[f"{model.__name__}.json"] = json.dumps(schema, indent=2, sort_keys=True) + "\n"
        definitions.update(schema.get("$defs", {}))
        definitions[model.__name__] = schema
    output["contracts.ts"] = (
        "// Generated by python -m services.core.export_contracts. Do not edit.\n"
        "// Decimal values serialize as strings; datetimes use ISO 8601 offsets.\n\n"
        + "\n\n".join(
            f"export type {name} = {ts_type(schema)};"
            for name, schema in sorted(definitions.items())
        )
        + "\n"
    )
    return output


if __name__ == "__main__":
    target = Path(__file__).resolve().parents[2] / "shared" / "schemas"
    target.mkdir(parents=True, exist_ok=True)
    for filename, content in artifacts().items():
        (target / filename).write_text(content, encoding="utf-8")
    print(f"Exported {len(MODELS)} JSON schemas and TypeScript contracts.")
